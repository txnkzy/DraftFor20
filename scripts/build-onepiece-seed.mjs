/**
 * Regenerates supabase/migrations/0029_onepiece.sql.
 *
 *   node scripts/build-onepiece-seed.mjs
 *
 * WHY THIS EXISTS RATHER THAN THE LIVE IMAGE CASCADE: a library category is
 * seeded once and played thousands of times, so its pictures belong in the
 * migration as literals — deterministic, no per-room fetch, and reviewable in
 * a diff. lib/images/resolve.ts is the runtime path for categories nobody
 * curated; this is the build-time path for one somebody did.
 *
 * WHY NOT WIKIPEDIA: probed first, and it does not work for this cast. Only
 * the nine Straw Hats have their own article. Everyone else REDIRECTS to a
 * group article and pageimages then returns that group's picture, so Jinbe
 * comes back as the Straw Hats line-up, Shanks as the Four Emperors and
 * Doflamingo as "List of One Piece pirates". A wrong picture is worse than
 * none, and the redirect makes it look successful. MyAnimeList has one
 * portrait per character and is keyless via Jikan.
 *
 * LICENCE: these are promotional character art, fair use, exactly like the
 * non-free Wikipedia infobox leads the cascade already serves. They are
 * stored as 'nonfree', so the freeOnly policy flag can drop them wholesale
 * if this ever ships somewhere that needs it.
 */

import { writeFileSync } from "node:fs";

const UA = { "User-Agent": "DraftFor20/1.0 (https://draftfor20.vercel.app; hello@draftfor20.app)" };
const JIKAN = "https://api.jikan.moe/v4/anime/21/characters"; // 21 = One Piece
const WANT = 80;

/**
 * MyAnimeList stores names as "Surname, Given".
 *
 * Rejoining as "Surname Given" is correct for Japanese-order names, which is
 * nearly the whole cast: "Roronoa, Zoro" is Roronoa Zoro. It is WRONG for the
 * handful written in western order — "Clown, Caesar" is Caesar Clown, not
 * Clown Caesar — and nothing in the payload distinguishes the two. So the
 * join is the default and the exceptions are listed by hand below.
 */
function joinName(raw) {
  const s = raw.replace(/\s+/g, " ").trim();
  const m = /^([^,]+),\s*(.+)$/.exec(s);
  return (m ? `${m[1].trim()} ${m[2].trim()}` : s).replace(/\s+/g, " ").trim();
}

/**
 * Play names.
 *
 * Two kinds of correction, and they are different things:
 *   1. joinName got it backwards (Caesar Clown).
 *   2. MAL uses the real name where the epithet is what anyone would
 *      recognise. In a bidding game the label has to be the one that makes a
 *      player react, so the Emperors and Admirals go by their titles.
 */
const RENAME = {
  "Clown Caesar": "Caesar Clown",       // (1) western-order name, reversed
  Kaidou: "Kaido",                      // standard English romanisation
  "Edward Newgate": "Whitebeard",       // (2) from here down
  "Marshall D. Teach": "Blackbeard",
  "Charlotte Linlin": "Big Mom",
  Borsalino: "Kizaru",
  Kuzan: "Aokiji",
  Sakazuki: "Akainu",
  Isshou: "Fujitora",
  Bentham: "Bon Clay",
  "Shimotsuki Ryuuma": "Ryuma",
  Otama: "Tama",
};

const res = await fetch(JIKAN, { headers: UA });
if (!res.ok) throw new Error(`jikan ${res.status} — MAL is often briefly down, just re-run`);
const { data = [] } = await res.json();

const seen = new Set();
const picked = [];
for (const c of data
  // a missing portrait falls back to MAL's question-mark placeholder, which
  // is a picture of nothing and worse than the generated card
  .filter((c) => c.character?.images?.jpg?.image_url && !/questionmark/i.test(c.character.images.jpg.image_url))
  .sort((a, b) => (b.favorites || 0) - (a.favorites || 0))) {
  const name = RENAME[joinName(c.character.name)] ?? joinName(c.character.name);
  const key = name.toLowerCase();
  if (seen.has(key)) continue;
  if (name.length < 2 || name.length > 60) continue; // df20_clean_text bounds
  // strip MAL's ?s= cache-buster: it is noise in a stored URL and the bare
  // path serves the same bytes (HEAD-checked when this list was built)
  const url = c.character.images.jpg.image_url.split("?")[0];
  if (!/^https:\/\/cdn\.myanimelist\.net\//.test(url)) continue;
  seen.add(key);
  picked.push({ name, url });
  if (picked.length >= WANT) break;
}

if (picked.length < 60) throw new Error(`only ${picked.length} characters — need 60 for a 30-slot roster`);
for (const p of picked) {
  if (/[\n\r$]/.test(p.name) || /[\n\r$]/.test(p.url)) throw new Error(`unsafe literal: ${p.name}`);
}

const sql = `-- ═══════════════════════════════════════════════════════════════════════════
-- DraftFor20 · 0029 · One Piece Characters, with portraits
--
-- GENERATED by scripts/build-onepiece-seed.mjs. Re-run that rather than
-- editing the lists below; the names and the URLs are positional and hand
-- editing one without the other slides every later picture onto the wrong
-- character.
--
-- The first library category to ship with images. 0028 carries image_url the
-- length of the chain (library -> room_pool -> room_deck -> lots), and the
-- leak rule is unchanged: the picture travels exactly where the name travels
-- and reaches a client only when the card is dealt.
--
-- Re-runnable. Both seeds upsert by normalised name.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── the image allowlist gains one host ────────────────────────────────────
-- Everything else about df20_clean_image_url is the 0028 text. MAL portraits
-- are fair-use promotional art, which is the same footing as the non-free
-- Wikipedia infobox leads already allowed, and they are stored as 'nonfree'
-- so a freeOnly policy can drop them as a set.
create or replace function public.df20_clean_image_url(p_in text)
returns text language plpgsql immutable
set search_path = public, pg_temp as $$
declare v text;
begin
  v := btrim(coalesce(p_in, ''));
  if length(v) = 0 or length(v) > 600 then return null; end if;
  if v !~ '^https://' then return null; end if;
  if v !~* '^https://(upload\\.wikimedia\\.org|commons\\.wikimedia\\.org|coverartarchive\\.org|covers\\.openlibrary\\.org|cdn\\.myanimelist\\.net)/' then
    return null;
  end if;
  if v ~ '[[:cntrl:]"''<>]' then return null; end if;
  return v;
end $$;

-- ── seeding a category that has pictures ──────────────────────────────────
-- Four arguments with NO defaults, so the two-argument df20_seed_category
-- survives as a real function rather than becoming an ambiguous call. Same
-- reasoning as the two df20_cache_wikipedia arities in 0028, and the
-- two-argument form is asserted by df20_selfcheck().
--
-- Indexed rather than FOREACH because the arrays are positional: a name that
-- fails df20_clean_text must not shift every following image up by one.
create or replace function public.df20_seed_category(
  p_name text, p_items text[], p_images text[], p_licenses text[]
) returns int language plpgsql security definer
set search_path = public, pg_temp as $fn$
declare v_id uuid; v_clean text; v_img text; v_lic text; v_n int; i int;
begin
  insert into public.category_library (name, name_norm)
  values (p_name, public.df20_norm_category(p_name))
  on conflict (name_norm) do update set name = excluded.name
  returning id into v_id;

  for i in 1 .. coalesce(array_length(p_items, 1), 0) loop
    v_clean := public.df20_clean_text(p_items[i], 60);
    if length(coalesce(v_clean, '')) >= 1 then
      v_img := public.df20_clean_image_url(
                 case when p_images is null or i > coalesce(array_length(p_images, 1), 0)
                      then null else p_images[i] end);
      v_lic := case when p_licenses is null or i > coalesce(array_length(p_licenses, 1), 0)
                    then null else p_licenses[i] end;
      if v_img is null then v_lic := null; end if;      -- keep the pair honest
      if v_lic is not null and v_lic not in ('free', 'nonfree') then v_lic := null; end if;

      -- on conflict UPDATE, not DO NOTHING: re-running has to be able to
      -- refresh a portrait whose URL moved, which DO NOTHING would silently
      -- skip for every name that already existed
      insert into public.category_library_items (library_id, name, image_url, image_license)
      values (v_id, v_clean, v_img, v_lic)
      on conflict (library_id, name)
        do update set image_url = excluded.image_url,
                      image_license = excluded.image_license;
    end if;
  end loop;

  select count(*) into v_n from public.category_library_items where library_id = v_id;
  return v_n;
end $fn$;
revoke all on function public.df20_seed_category(text, text[], text[], text[]) from anon, authenticated;

-- ── One Piece Characters · ${picked.length} items ${"─".repeat(Math.max(1, 34 - String(picked.length).length))}
select public.df20_seed_category(
  'One Piece Characters',
  string_to_array($it$${picked.map((p) => p.name).join("\n")}$it$, E'\\n'),
  string_to_array($im$${picked.map((p) => p.url).join("\n")}$im$, E'\\n'),
  array_fill('nonfree'::text, array[${picked.length}]));

select public.df20_add_alias('One Piece Characters',
  array['one piece', 'onepiece', 'one piece cast', 'straw hats', 'straw hat pirates']);

-- ── assert the pictures actually landed ───────────────────────────────────
-- A silent zero here would mean every portrait failed df20_clean_image_url
-- and the whole category quietly degraded to generated cards.
do $$
declare v_total int; v_imgs int;
begin
  select count(*), count(image_url) into v_total, v_imgs
    from public.category_library_items i
    join public.category_library l on l.id = i.library_id
   where l.name_norm = public.df20_norm_category('One Piece Characters');

  if v_total < 60 then
    raise exception 'DF20_ONEPIECE_TOO_SMALL: % items, need 60 for a 30-slot roster', v_total;
  end if;
  if v_imgs < v_total then
    raise exception 'DF20_ONEPIECE_MISSING_IMAGES: % of % items have no picture',
      v_total - v_imgs, v_total;
  end if;
  raise notice 'One Piece Characters: % items, all with portraits', v_total;
end $$;
`;

writeFileSync(new URL("../supabase/migrations/0029_onepiece.sql", import.meta.url), sql);
console.log(`wrote 0029_onepiece.sql — ${picked.length} characters, ${picked.length} portraits`);
console.log(picked.map((p, i) => `${String(i + 1).padStart(3)}  ${p.name}`).join("\n"));
